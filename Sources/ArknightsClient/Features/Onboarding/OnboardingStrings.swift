	}
	static func progressVersion(_ version: String) -> LocalizedStringResource {
		.onboardingProgressVersion(version)
	}

	static func stepTitle(_ step: OnboardingStep) -> LocalizedStringResource {
		switch step {
		case .welcome: .onboardingProgressStepWelcome
		case .installation: .onboardingProgressStepInstallation
		case .game: .onboardingProgressStepGame
		case .personalization: .onboardingProgressStepPersonalization
		case .icons: .onboardingProgressStepIcons
		case .extras: .onboardingProgressStepExtras
		case .finish: .onboardingProgressStepFinish
		}
	}

	static func statusTitle(_ state: OnboardingUpdateState) -> LocalizedStringResource {
		switch state {
		case .checking: .onboardingWelcomeStatusChecking
		case .current: .onboardingWelcomeStatusCurrent
		case .updateRequired: .onboardingWelcomeStatusUpdateRequired
		case .checkFailed: .onboardingWelcomeStatusCheckFailed
		}
	}

	static func displayMode(_ mode: GameDisplayMode) -> LocalizedStringResource {
		switch mode {
		case .fullscreen: .onboardingGameDisplayModeFullscreen
		case .windowed: .onboardingGameDisplayModeWindowed
		case .borderlessWindow: .onboardingGameDisplayModeBorderless
		}
	}

	static func regionDetail(_ region: GameRegion) -> LocalizedStringResource {
		switch region {
