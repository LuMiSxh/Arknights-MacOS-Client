"""Render every output of the support-code catalog from `support-codes.json`.

The catalog is the only hand-written source. The outputs are the help pages, the
registry, the legacy redirects, the issue-form code list, and the Swift enum.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from lib.common import fail
from lib.generated_blocks import render_documents
from lib.project_config import (
    ISSUE_REPORT_TEMPLATE,
    SUPPORT_CODE_ARTICLES,
    SUPPORT_CODE_CATALOG,
    SUPPORT_CODE_SWIFT,
)

GENERATED_NOTE = (
    "Generated by scripts/support_codes.py from support-codes.json. Do not edit."
)
CODE_PATTERN = re.compile(r"^[A-Z]{2}-[A-Z]{3}$")
LEGACY_PATTERN = re.compile(r"^[A-Z]+$")
SWIFT_NAME_PATTERN = re.compile(r"^[a-z][A-Za-z0-9]*$")
# Domains in display order. Each code starts with the two-letter prefix of its domain.
DOMAIN_PREFIXES = {
    "service": "SV",
    "network": "NW",
    "installation": "IN",
    "files": "FS",
    "runtime": "RT",
    "game": "GM",
    "update": "UP",
    "customization": "UI",
}
# A retired code moves into the `legacy` list of its successor and leaves the catalog.
# The generator renders active codes only, so a retired entry would vanish silently.
STATUSES = ("active",)
ENTRY_KEYS = {
    "code",
    "swiftName",
    "domain",
    "title",
    "status",
    "summary",
    "action",
    "allowsRetry",
    "allowsRepair",
    "causes",
    "steps",
    "report",
    "legacy",
}
ISSUE_BEGIN = "  # support-codes:begin code\n"
ISSUE_END = "  # support-codes:end code\n"
ISSUE_BLOCK = re.compile(
    re.escape(ISSUE_BEGIN) + r"(?P<body>.*?)" + re.escape(ISSUE_END), re.DOTALL
)
NONE_OPTION = "None / not shown"
RETRY_NOTE = (
    "Select **Retry** after you finish these steps. Retry repeats the failed operation. "
    "It keeps valid downloads and game files."
)
REPAIR_NOTE = (
    "If the steps do not help, select **Repair**. Repair checks the installed game files "
    "and asks you to confirm before it changes them."
)
REPORT_FORM_NOTE = (
    "Choose **Help → Report a Problem…** if these steps do not solve the problem. "
    "The report adds the code, the launcher version, and your Mac details."
)
DIAGNOSTICS_NOTE = "A maintainer can ask for a diagnostics file. Then choose **Help → Save Diagnostics…**"
LEGACY_SUMMARY = "This code was replaced by more specific codes."
LEGACY_SINGLE_SUMMARY = "This code was replaced by a new code."
LEGACY_ORDER = 900
# The launcher release that retired every legacy code.
LEGACY_RETIRED_IN = "0.8.0"
# The index keeps its prose by hand; the generator fills only the blocks it names.
INDEX_PAGE = SUPPORT_CODE_ARTICLES / "README.md"
INDEX_NAMESPACE = "support-codes"


@dataclass(frozen=True)
class SupportCodeEntry:
    code: str
    swift_name: str
    domain: str
    title: str
    status: str
    summary: str
    action: str
    allows_retry: bool
    allows_repair: bool
    causes: tuple[str, ...]
    steps: tuple[str, ...]
    report: str
    legacy: tuple[str, ...]

    @property
    def lower(self) -> str:
        return self.code.lower()

    @property
    def sort_key(self) -> tuple[int, str]:
        return (list(DOMAIN_PREFIXES).index(self.domain), self.code)


@dataclass(frozen=True)
class Catalog:
    entries: tuple[SupportCodeEntry, ...]

    @property
    def active(self) -> tuple[SupportCodeEntry, ...]:
        return tuple(entry for entry in self.entries if entry.status == "active")

    @property
    def legacy_codes(self) -> tuple[str, ...]:
        return tuple(sorted({code for entry in self.entries for code in entry.legacy}))

    def successors(self, legacy: str) -> tuple[SupportCodeEntry, ...]:
        return tuple(entry for entry in self.active if legacy in entry.legacy)


def load_catalog(path: Path) -> Catalog:
    """Parse and validate the catalog; fail with the first contract it breaks."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        fail(f"{path}: cannot read the support-code catalog: {error}")
    return parse_catalog(data, str(path))


def parse_catalog(data: object, source: str) -> Catalog:
    if not isinstance(data, dict) or set(data) != {"codes"}:
        fail(f"{source}: the catalog must be an object with one key, codes")
    if not isinstance(data["codes"], list):
        fail(f"{source}: codes must be a list")
    entries = tuple(
        _parse_entry(item, f"{source} entry {index}")
        for index, item in enumerate(data["codes"], start=1)
    )
    _validate(entries, source)
    return Catalog(tuple(sorted(entries, key=lambda entry: entry.sort_key)))


def _parse_entry(item: object, where: str) -> SupportCodeEntry:
    if not isinstance(item, dict) or set(item) != ENTRY_KEYS:
        fail(f"{where}: keys must be exactly {', '.join(sorted(ENTRY_KEYS))}")
    entry = SupportCodeEntry(
        code=_text(item["code"], "code", where),
        swift_name=_text(item["swiftName"], "swiftName", where),
        domain=_text(item["domain"], "domain", where),
        title=_text(item["title"], "title", where),
        status=_text(item["status"], "status", where),
        summary=_text(item["summary"], "summary", where),
        action=_text(item["action"], "action", where),
        allows_retry=_flag(item["allowsRetry"], "allowsRetry", where),
        allows_repair=_flag(item["allowsRepair"], "allowsRepair", where),
        causes=_texts(item["causes"], "causes", where),
        steps=_texts(item["steps"], "steps", where),
        report=_text(item["report"], "report", where),
        legacy=_texts(item["legacy"], "legacy", where, allow_empty=True),
    )
    return entry


def _text(value: object, field: str, where: str) -> str:
    if not isinstance(value, str) or not value.strip():
        fail(f"{where}: {field} must be a non-empty string")
    return value


def _texts(
    value: object, field: str, where: str, *, allow_empty: bool = False
) -> tuple[str, ...]:
    if not isinstance(value, list) or (not value and not allow_empty):
        fail(f"{where}: {field} must be a non-empty list of strings")
    if not all(isinstance(item, str) and item.strip() for item in value):
        fail(f"{where}: {field} must contain only non-empty strings")
    if len(set(value)) != len(value):
        fail(f"{where}: {field} must not repeat a value")
    return tuple(value)


def _flag(value: object, field: str, where: str) -> bool:
    if not isinstance(value, bool):
        fail(f"{where}: {field} must be true or false")
    return value


def _validate(entries: tuple[SupportCodeEntry, ...], source: str) -> None:
    codes = [entry.code for entry in entries]
    if len(set(codes)) != len(codes):
        fail(f"{source}: codes must be unique")
    names = [entry.swift_name for entry in entries]
    if len(set(names)) != len(names):
        fail(f"{source}: swiftName values must be unique")
    for entry in entries:
        where = f"{source} {entry.code}"
        if not CODE_PATTERN.match(entry.code):
            fail(f"{where}: a code must match XX-XXX with uppercase letters")
        if DOMAIN_PREFIXES.get(entry.domain) != entry.code[:2]:
            fail(f"{where}: the code prefix must match its domain")
        if not SWIFT_NAME_PATTERN.match(entry.swift_name):
            fail(f"{where}: swiftName must be lowerCamelCase")
        if entry.status not in STATUSES:
            fail(f"{where}: status must be active")
        if "|" in entry.action:
            fail(f"{where}: action must not contain a pipe")
        if not (
            entry.summary.isascii()
            and '"' not in entry.summary
            and "\\" not in entry.summary
        ):
            fail(f"{where}: summary must be plain ASCII without quotes or backslashes")
        for legacy in entry.legacy:
            if not LEGACY_PATTERN.match(legacy):
                fail(f"{where}: legacy code {legacy} must be uppercase letters only")


def render_outputs(root: Path, catalog: Catalog) -> dict[Path, str]:
    """Return every generated file, keyed by its path relative to `root`."""
    outputs: dict[Path, str] = {}
    active = catalog.active
    for order, entry in enumerate(active, start=1):
        outputs[SUPPORT_CODE_ARTICLES / f"{entry.lower}.md"] = render_code_page(
            entry, order
        )
    registry = [{"code": entry.code, "domain": entry.domain} for entry in active]
    outputs[SUPPORT_CODE_ARTICLES / "registry.json"] = (
        json.dumps(registry, indent=2) + "\n"
    )
    for legacy in catalog.legacy_codes:
        page = SUPPORT_CODE_ARTICLES / f"{legacy.lower()}.md"
        outputs[page] = render_legacy_page(legacy, catalog.successors(legacy))
    outputs[INDEX_PAGE] = render_index(root, catalog)
    outputs[SUPPORT_CODE_SWIFT] = render_swift(catalog)
    issue = (root / ISSUE_REPORT_TEMPLATE).read_text(encoding="utf-8")
    outputs[ISSUE_REPORT_TEMPLATE] = _fill_issue_block(issue, catalog)
    return outputs


def render_code_page(entry: SupportCodeEntry, order: int) -> str:
    title = json.dumps(f"{entry.code}: {entry.title}")
    lines = [
        "---",
        f"title: {title}",
        f"description: {json.dumps(entry.summary)}",
        f"order: {order}",
        "audience: users",
        f"code: {entry.code}",
        f"domain: {entry.domain}",
        "---",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
        entry.summary,
        "",
        "## What happened",
        "",
        "Possible causes:",
        "",
        *_bullets(entry.causes),
        "",
        "## What you can do",
        "",
        *_numbered(entry.steps),
        "",
    ]
    if entry.allows_retry:
        lines += [RETRY_NOTE, ""]
    if entry.allows_repair:
        lines += [REPAIR_NOTE, ""]
    lines += [
        "## Report the problem",
        "",
        REPORT_FORM_NOTE,
        "",
        entry.report,
        "",
        DIAGNOSTICS_NOTE,
        "",
    ]
    return "\n".join(lines)


def render_legacy_page(legacy: str, successors: tuple[SupportCodeEntry, ...]) -> str:
    if len(successors) == 1:
        (successor,) = successors
        body = [
            f"Launcher {LEGACY_RETIRED_IN} replaced {legacy} with **{successor.code}**.",
            "",
            f"[{successor.code}]({successor.lower}.md): {successor.summary}",
        ]
    else:
        body = [
            "Open the page for the code that matches your error:",
            "",
            *[
                f"- [{entry.code}]({entry.lower}.md): {entry.summary}"
                for entry in successors
            ],
        ]
    lines = [
        "---",
        f"title: {legacy} has moved",
        f"description: {json.dumps(LEGACY_SINGLE_SUMMARY if len(successors) == 1 else LEGACY_SUMMARY)}",
        f"order: {LEGACY_ORDER}",
        "audience: users",
        "hidden: true",
        "---",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
        *body,
        "",
    ]
    return "\n".join(lines)


def render_index(root: Path, catalog: Catalog) -> str:
    """Fill the generated tables of the error-code index; the prose stays hand-written."""
    blocks = {"codes": _code_tables(catalog), "retired": _retired_table(catalog)}
    return render_documents(root, {INDEX_PAGE: blocks}, INDEX_NAMESPACE)[INDEX_PAGE]


def _code_tables(catalog: Catalog) -> str:
    tables = []
    for domain in DOMAIN_PREFIXES:
        entries = [entry for entry in catalog.active if entry.domain == domain]
        if not entries:
            continue
        rows = [
            f"| [{entry.code}]({entry.lower}.md) | {entry.title} | {entry.action} |"
            for entry in entries
        ]
        header = ["| Code | Problem | What to do |", "| --- | --- | --- |"]
        tables.append("\n".join([f"### {domain.capitalize()}", "", *header, *rows]))
    return "\n\n".join(tables) + "\n"


def _retired_table(catalog: Catalog) -> str:
    rows = []
    for legacy in catalog.legacy_codes:
        successors = ", ".join(
            f"[{entry.code}]({entry.lower}.md)" for entry in catalog.successors(legacy)
        )
        rows.append(f"| {legacy} | {successors} |")
    return "\n".join(["| Old code | New code |", "| --- | --- |", *rows]) + "\n"


def render_swift(catalog: Catalog) -> str:
    active = catalog.active
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        f"// {GENERATED_NOTE}",
        "",
        "import Foundation",
        "",
        "/// The recovery owner that a support code belongs to.",
        "package enum SupportDomain: String, CaseIterable, Codable, Sendable {",
        *[f"\tcase {domain}" for domain in DOMAIN_PREFIXES],
        "}",
        "",
        "/// Stable public identifiers for documented launcher failures.",
        "package enum SupportCode: String, CaseIterable, Codable, Sendable {",
        *[f'\tcase {entry.swift_name} = "{entry.code}"' for entry in active],
        "",
        "\t/// The recovery owner of the code.",
        "\tpackage var domain: SupportDomain {",
        "\t\tswitch self {",
        *_swift_cases(active, lambda entry: f".{entry.domain}"),
        "\t\t}",
        "\t}",
        "",
        "\t/// The default user message for the code.",
        "\tpackage var summary: String {",
        "\t\tswitch self {",
        *_swift_cases(active, lambda entry: f'"{entry.summary}"'),
        "\t\t}",
        "\t}",
        "",
        "\t/// Whether the failure window offers Retry for the code.",
        "\tpackage var allowsRetry: Bool {",
        "\t\tswitch self {",
        *_swift_cases(active, lambda entry: str(entry.allows_retry).lower()),
        "\t\t}",
        "\t}",
        "",
        "\t/// Whether the failure window offers Repair for the code.",
        "\tpackage var allowsRepair: Bool {",
        "\t\tswitch self {",
        *_swift_cases(active, lambda entry: str(entry.allows_repair).lower()),
        "\t\t}",
        "\t}",
        "",
        "\tpackage var troubleshootingURL: URL {",
        "\t\tSupportLinks.documentationRoot.appending(",
        '\t\t\tpath: "help/errors/\\(rawValue.lowercased())/"',
        "\t\t)",
        "\t}",
        "",
        "\tstatic func hasValidSyntax(_ value: String) -> Bool {",
        "\t\tvalue.wholeMatch(of: /[A-Z]{2}-[A-Z]{3}/) != nil",
        "\t}",
        "",
        "\tstatic func isPublished(_ value: String) -> Bool {",
        "\t\tSupportCode(rawValue: value) != nil",
        "\t}",
        "}",
        "",
    ]
    return "\n".join(lines)


def _swift_cases(entries, value) -> list[str]:
    lines: list[str] = []
    for entry in entries:
        lines += [f"\t\tcase .{entry.swift_name}:", f"\t\t\t{value(entry)}"]
    return lines


def _bullets(items: tuple[str, ...]) -> list[str]:
    return [f"- {item}" for item in items]


def _numbered(items: tuple[str, ...]) -> list[str]:
    return [f"{index}. {item}" for index, item in enumerate(items, start=1)]


def render_issue_block(catalog: Catalog) -> str:
    options = [NONE_OPTION, *(entry.code for entry in catalog.active)]
    lines = [
        "  - type: dropdown",
        "    id: code",
        "    attributes:",
        "      label: Error code",
        "      description: Select the code shown by the launcher. Choose None / not shown when the launcher showed no code.",
        "      options:",
        *[f"        - {option}" for option in options],
    ]
    return "\n".join(lines) + "\n"


def _fill_issue_block(text: str, catalog: Catalog) -> str:
    if len(ISSUE_BLOCK.findall(text)) != 1:
        fail(f"{ISSUE_REPORT_TEMPLATE}: needs exactly one support-codes block")
    block = render_issue_block(catalog)
    return ISSUE_BLOCK.sub(lambda _: ISSUE_BEGIN + block + ISSUE_END, text)


def _generated_files(root: Path) -> list[Path]:
    """Return generated pages that still carry the generator note."""
    return sorted(
        path.relative_to(root)
        for path in (root / SUPPORT_CODE_ARTICLES).glob("*.md")
        if GENERATED_NOTE in path.read_text(encoding="utf-8")
    )


def check(root: Path) -> list[str]:
    """Return one message for each generated file that is missing, stale, or orphaned."""
    catalog = load_catalog(root / SUPPORT_CODE_CATALOG)
    outputs = render_outputs(root, catalog)
    problems: list[str] = []
    for path, text in outputs.items():
        target = root / path
        if not target.is_file():
            problems.append(f"{path}: missing; run just generate")
        elif target.read_text(encoding="utf-8") != text:
            problems.append(f"{path}: generated file is stale; run just generate")
    for path in _generated_files(root):
        if path not in outputs:
            problems.append(f"{path}: no catalog entry; run just generate")
    return problems


def regenerate(root: Path) -> list[Path]:
    """Write the outputs that differ on disk and remove orphaned generated files."""
    catalog = load_catalog(root / SUPPORT_CODE_CATALOG)
    outputs = render_outputs(root, catalog)
    changed: list[Path] = []
    for path in _generated_files(root):
        if path not in outputs:
            (root / path).unlink()
            changed.append(path)
    for path, text in outputs.items():
        target = root / path
        if target.is_file() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        changed.append(path)
    return changed
