"""The table of resources that the app bundle holds.

`Sources/ArknightsCore/Shared/Resources/BundledResource.swift` names the resources
that the app reads. This table names the same resources with their sources and
formats. `registry_drift` reports every difference between the two.

Encoding rule: a file that the build copies verbatim from the repository stays
`identity`, so the bundle holds the same bytes as the source. A document that the
build generates uses `deflate` (raw deflate of UTF-8 text).
"""

import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, cast

from lib.common import copy_file, fail, remove_path
from lib.licenses import BUNDLE_NOTICES_NAME
from lib.project_config import RUNTIME_CONFIG, ProjectConfiguration

SWIFT_REGISTRY_SUBPATH = Path("Shared/Resources/BundledResource.swift")

type ResourceKind = Literal["file", "directory"]
type ResourceOrigin = Literal["app", "package"]
type ResourceEncoding = Literal["identity", "deflate"]

ORIGIN_APP: ResourceOrigin = "app"
ORIGIN_PACKAGE: ResourceOrigin = "package"
IDENTITY: ResourceEncoding = "identity"
DEFLATE: ResourceEncoding = "deflate"

_DECLARATION = re.compile(
    r"static\s+let\s+\w+\s*=\s*BundledResource\(\s*"
    r'(?P<kind>file|directory):\s*"(?P<path>[^"]+)",\s*'
    r"origin:\s*\.(?P<origin>app|package)"
    r"(?:,\s*encoding:\s*\.(?P<encoding>identity|deflate))?\s*\)"
)

type ResourceKey = tuple[str, ResourceKind, ResourceOrigin, ResourceEncoding]


@dataclass(frozen=True, slots=True)
class StagedResource:
    """One file or directory in `Contents/Resources`.

    `source` is the repository path that the build copies, or `None` when the
    build generates the resource. `swift_reads` is true when the app loads the
    resource by name, so `BundledResource.swift` must list it.
    """

    path: str
    kind: ResourceKind
    origin: ResourceOrigin
    encoding: ResourceEncoding = IDENTITY
    source: str | None = None
    swift_reads: bool = True

    @property
    def key(self) -> ResourceKey:
        return (self.path, self.kind, self.origin, self.encoding)


FIXED_RESOURCES = (
    StagedResource("LICENSE", "file", ORIGIN_APP, source="LICENSE"),
    StagedResource("CHANGELOG.md", "file", ORIGIN_APP, source="CHANGELOG.md"),
    StagedResource(
        "RUNTIME.json", "file", ORIGIN_APP, source=RUNTIME_CONFIG.as_posix()
    ),
    # Generated by `lib.licenses.stage_bundle`.
    StagedResource(BUNDLE_NOTICES_NAME, "file", ORIGIN_APP, DEFLATE),
    StagedResource(
        "SupportArticles", "directory", ORIGIN_APP, source="docs/help/errors"
    ),
    # Built by `build_compatibility.py`.
    StagedResource("Compatibility", "directory", ORIGIN_APP),
)


def staged_resources(configuration: ProjectConfiguration) -> tuple[StagedResource, ...]:
    """Return every resource of the bundle."""
    icon_filename = configuration.product.icon_filename
    # Info.plist names the icon, so the app never loads these two by name.
    icons = (
        StagedResource(
            icon_filename,
            "file",
            ORIGIN_APP,
            source=f"Resources/{icon_filename}",
            swift_reads=False,
        ),
        StagedResource(
            "Assets.car",
            "file",
            ORIGIN_APP,
            source="Resources/Assets.car",
            swift_reads=False,
        ),
    )
    package = tuple(
        StagedResource(
            path.name,
            "directory" if path.is_dir() else "file",
            ORIGIN_PACKAGE,
            source=str(path.relative_to(configuration.project_directory)),
        )
        for path in configuration.copied_resource_source_paths
    )
    return (*icons, *FIXED_RESOURCES, *package)


def swift_registry_path(configuration: ProjectConfiguration) -> Path:
    """Return the repository path of `BundledResource.swift`."""
    return configuration.package.resource_target_path / SWIFT_REGISTRY_SUBPATH


def swift_registry(source: str) -> tuple[ResourceKey, ...]:
    """Parse the resource declarations of `BundledResource.swift`."""
    return tuple(
        (
            match["path"],
            cast("ResourceKind", match["kind"]),
            cast("ResourceOrigin", match["origin"]),
            cast("ResourceEncoding", match["encoding"] or IDENTITY),
        )
        for match in _DECLARATION.finditer(source)
    )


def registry_drift(
    configuration: ProjectConfiguration, swift_source: str | None = None
) -> list[str]:
    """Return the differences between the Swift registry and the staging table."""
    registry = swift_registry_path(configuration)
    if swift_source is None:
        swift_source = (configuration.project_directory / registry).read_text(
            encoding="utf-8"
        )
    declared = swift_registry(swift_source)
    problems: list[str] = []
    paths = [entry[0] for entry in declared]
    if len(paths) != len(set(paths)):
        problems.append(f"{registry} declares a path more than once")

    staged = staged_resources(configuration)
    staged_paths = [resource.path for resource in staged]
    if len(staged_paths) != len(set(staged_paths)):
        problems.append("the staged resources contain duplicate paths")

    expected = {resource.key for resource in staged if resource.swift_reads}
    for entry in sorted(set(declared) - expected):
        problems.append(
            f"{registry} lists a resource the build does not stage: {entry}"
        )
    for entry in sorted(expected - set(declared)):
        problems.append(
            f"the build stages a resource {registry} does not list: {entry}"
        )
    return problems


def app_resources(configuration: ProjectConfiguration) -> tuple[tuple[Path, Path], ...]:
    """Return the (source, destination) copies of the app-origin resources."""
    project = configuration.project_directory
    entries = [
        (project / resource.source, Path(resource.path))
        for resource in staged_resources(configuration)
        if resource.source is not None
    ]
    destinations = [destination for _, destination in entries]
    if len(destinations) != len(set(destinations)):
        fail("application resources contain duplicate destinations")
    return tuple(entries)


def copy_resource(source: Path, destination: Path) -> None:
    if source.is_dir():
        shutil.copytree(source, destination)
    elif source.is_file():
        copy_file(source, destination)
    else:
        fail(f"required resource not found: {source}")


def stage_app_resources(configuration: ProjectConfiguration, resources: Path) -> None:
    """Copy the app-origin resources that have a source into `resources`.

    An earlier copy is replaced, so staging again leaves the same tree. Compatibility
    is built by `build_compatibility.py`, and the notices by `stage_bundle`.
    """
    for source, destination in app_resources(configuration):
        remove_path(resources / destination)
        copy_resource(source, resources / destination)
